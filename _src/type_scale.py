"""Builds assets/type-scale.css: every font size in the site's stylesheets x FACTOR.
Layout (rem/px spacing) is untouched; only type shrinks. Re-run via build.py."""
import re, os

FACTOR = 0.9
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ['assets/base.css', 'assets/site.css', 'assets/theme.css', 'assets/case.css', 'assets/projects/yi/yx.css']


def strip_comments(s):
    return re.sub(r'/\*.*?\*/', '', s, flags=re.S)


def blocks(s):
    """yield (prelude, body) for top-level blocks"""
    i, n = 0, len(s)
    while i < n:
        j = s.find('{', i)
        if j < 0: return
        pre = s[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if s[k] == '{': depth += 1
            elif s[k] == '}': depth -= 1
            k += 1
        yield pre.split(';')[-1].strip(), s[j + 1:k - 1]
        i = k


def scaled(val):
    v = val.strip()
    imp = ''
    if v.endswith('!important'): v, imp = v[:-10].strip(), ' !important'
    if re.search(r'(?<!r)em\b|%|inherit|initial|unset|var\(|^(small|medium|large|larger|smaller)', v): return None
    if not re.search(r'\d', v): return None
    return f'calc(({v}) * {FACTOR}){imp}'


def font_shorthand(val):
    m = re.search(r'(?<![\w.-])(\d*\.?\d+)(px|rem|vw)(?=[\s/])', val)
    if not m: return None
    size = f'{float(m.group(1)) * FACTOR:.4g}{m.group(2)}'
    return val[:m.start()] + size + val[m.end():]


def rules(css):
    out = []
    for pre, body in blocks(css):
        if pre.startswith('@media') or pre.startswith('@supports'):
            inner = rules(body)
            if inner: out.append(f'{pre}{{\n{inner}\n}}')
            continue
        if pre.startswith('@'): continue
        if re.fullmatch(r'\s*(html|:root)\s*', pre): continue   # root size drives rem layout: leave it
        decls = []
        for d in body.split(';'):
            if ':' not in d: continue
            p, v = d.split(':', 1); p = p.strip().lower()
            if p == 'font-size':
                s = scaled(v)
                if s: decls.append(f'font-size:{s}')
            elif p == 'font':
                s = font_shorthand(v.strip())
                if s: decls.append(f'font:{s}')
        if decls: out.append(f'{pre}{{{";".join(decls)}}}')
    return '\n'.join(out)


def build():
    parts = [f'/* generated by _src/type_scale.py — all type x {FACTOR} */']
    for src in SOURCES:
        p = os.path.join(ROOT, src)
        if os.path.exists(p):
            parts.append(f'/* {src} */\n' + rules(strip_comments(open(p, encoding='utf-8').read())))
    open(os.path.join(ROOT, 'assets', 'type-scale.css'), 'w', encoding='utf-8').write('\n'.join(parts) + '\n')


if __name__ == '__main__':
    build()
